def _split(script: str) -> list[str]:
    return [s.strip() for s in script.split(";") if s.strip()]


class Cursor:
    """The subset of the DB-API cursor the store uses, the same on both engines."""

    def __init__(self, rows: list[tuple] | None, rowcount: int):
        self._rows = rows or []
        self.rowcount = rowcount

    def fetchone(self) -> tuple | None:
        return self._rows[0] if self._rows else None

    def fetchall(self) -> list[tuple]:
        return list(self._rows)

    def __iter__(self):
        return iter(self._rows)


class Conn:
    def __init__(self, raw: Any, dialect: str):
        self.raw, self.dialect = raw, dialect

    def _sql(self, sql: str) -> str:
        return _QMARK.sub("%s", sql) if self.dialect == "postgres" else sql

    def execute(self, sql: str, params: Sequence[Any] = ()) -> Cursor:
        if self.dialect == "sqlite":
            cur = self.raw.execute(sql, tuple(params))
            rows = cur.fetchall() if cur.description else None
            return Cursor(rows, cur.rowcount)
        with self.raw.cursor() as cur:
            cur.execute(self._sql(sql), tuple(params))
            rows = cur.fetchall() if cur.description else None
            return Cursor(rows, cur.rowcount)

    def executemany(self, sql: str, seq: Iterable[Sequence[Any]]) -> None:
        seq = [tuple(p) for p in seq]
        if not seq:
            return
        if self.dialect == "sqlite":
            self.raw.executemany(sql, seq)
            return
        with self.raw.cursor() as cur:
            cur.executemany(self._sql(sql), seq)

    def executescript(self, script: str) -> None:
        for stmt in _split(script):
            self.execute(stmt)


class Database:
    """Connections and migrations for one target: a file path or a postgres URL."""

    def __init__(self, target: str | Path):
        t = str(target)
        self.dialect = "postgres" if t.startswith(("postgresql://", "postgres://")) else "sqlite"
        self.target = t
        self._lock = threading.Lock()
        self._pool = None
        if self.dialect == "sqlite":
            Path(t).parent.mkdir(parents=True, exist_ok=True)
        else:
            from psycopg_pool import ConnectionPool

            self._pool = ConnectionPool(t, min_size=1, max_size=5, open=True, kwargs={"autocommit": False})
        self.migrate()

    @property
    def label(self) -> str:
        """Where the data lives, without credentials (for /ready and logs)."""
        if self.dialect == "sqlite":
            return f"sqlite:{Path(self.target).name}"
        return "postgres:" + re.sub(r"//[^@/]*@", "//***@", self.target).split("?")[0].rsplit("/", 1)[-1]

    @contextmanager
    def conn(self):
        if self.dialect == "sqlite":
            raw = sqlite3.connect(self.target, check_same_thread=False, timeout=30)
            raw.execute("PRAGMA foreign_keys = ON")
            try:
                yield Conn(raw, "sqlite")
                raw.commit()
            except Exception:
                raw.rollback()
                raise
            finally:
                raw.close()
        else:
            with self._pool.connection() as raw:  # commits on success, rolls back on error
                yield Conn(raw, "postgres")

    def migrate(self) -> list[int]:
        applied: list[int] = []
        with self._lock, self.conn() as c:
            c.execute(
                "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL,"
                " applied_at TEXT NOT NULL)"
            )
            done = {r[0] for r in c.execute("SELECT version FROM schema_migrations").fetchall()}
            if self.dialect == "sqlite" and 1 not in done:
                # Databases created before migrations existed: add the column the baseline expects.
                c.executescript(MIGRATIONS[0].sqlite)
                cols = {r[1] for r in c.execute("PRAGMA table_info(runs)").fetchall()}
                if "profile" not in cols:
                    c.execute("ALTER TABLE runs ADD COLUMN profile TEXT")
            for m in MIGRATIONS:
                if m.version in done:
                    continue
                c.executescript(m.sqlite if self.dialect == "sqlite" else m.postgres)
                c.execute(
                    "INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, CURRENT_TIMESTAMP)",
                    (m.version, m.name),
                )
                applied.append(m.version)
        if applied:
            log.info("applied migrations %s on %s", applied, self.label)
        return applied

    def schema_version(self) -> int:
        with self.conn() as c:
            row = c.execute("SELECT MAX(version) FROM schema_migrations").fetchone()
        return int(row[0] or 0)

    def ping(self) -> bool:
        try:
            with self.conn() as c:
                c.execute("SELECT 1")
            return True
        except Exception:  # noqa: BLE001 - readiness reports, never raises
            return False

    def close(self) -> None:
        if self._pool is not None:
            self._pool.close()
