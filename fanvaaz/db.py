"""One database interface for two backends.

* SQLite: a single file, zero setup. Used on a laptop and in offline CI.
* PostgreSQL (Cloud SQL in production): set FANVAAZ_DATABASE_URL. Several
  Cloud Run instances can share it, and pgvector stores the RAG embeddings.

The rest of the code writes portable SQL with `?` placeholders and the
`INSERT ... ON CONFLICT` upsert form that both engines understand. This module
translates placeholders for psycopg and applies versioned migrations, recorded
in `schema_migrations`, so a deploy can never run half a schema.
"""

